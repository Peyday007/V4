/**
 * Put a room in front of a prospect.
 *
 * Refuses rather than throws, because the caller is an API route that has
 * already marked the room sent and needs to report what happened rather than
 * unwind. Every refusal names the specific reason, so nothing here can fail
 * silently and look like a delivery.
 */
export async function sendRoomEmail(options: {
  orgId: string;
  roomId: string;
  contactId: string;
  senderId?: string | null;
}): Promise<{ sent: boolean; reason?: string; messageId?: string; audience?: Audience }> {
  // A deal room built on a sandbox opportunity is a page about an invented
  // company. Delivering it is refused before the room is even loaded.
  await assertProductionOnly(
    { roomId: options.roomId, contactId: options.contactId },
    'delivering a deal room',
  );

  const room = await prisma.dealRoom.findFirst({
    where: { id: options.roomId, orgId: options.orgId },
    include: { route: { select: { id: true } } },
  });
  if (!room) return { sent: false, reason: 'That room is not on this account.' };

  const contact = await prisma.contact.findFirst({
    where: { id: options.contactId, orgId: options.orgId },
  });
  if (!contact) return { sent: false, reason: 'That contact is not on this account.' };
  if (!contact.email) return { sent: false, reason: 'No email address on that contact.' };
  if (!contact.consentToEmail) return { sent: false, reason: 'That contact has withdrawn email consent.' };

  const suppressed = await prisma.suppressionEntry.findFirst({
    where: {
      orgId: options.orgId,
      contactId: options.contactId,
      scope: { in: ['DO_NOT_EMAIL', 'DO_NOT_CONTACT'] },
    },
  });
  if (suppressed) return { sent: false, reason: `Suppressed for email: ${suppressed.reason}` };

  const config = await getOrgConfig(options.orgId);
  const choice = chooseAudience([contact], { allowGenericInbox: config.outreachRules.allowGenericInboxFallback });
  if (!choice) {
    return {
      sent: false,
      reason: 'Only a general inbox is available and generic-inbox fallback is switched off for this organisation.',
    };
  }

  const content = room.content as unknown as RoomContent;
  const url = `${env().APP_URL.replace(/\/$/, '')}/room/${room.token}`;
  const sender = await prisma.user.findFirst({
    where: { id: options.senderId ?? undefined, orgId: options.orgId },
    select: { name: true },
  });

  const draft = draftRoomEmail({
    content,
    choice,
    url,
    senderName: sender?.name ?? 'The team',
  });

  if (draft.blockers.length > 0) {
    return { sent: false, reason: `Not sent: ${draft.blockers.join(' ')}` };
  }

  const result = await getEmail().send({ to: contact.email, subject: draft.subject, body: draft.body });

  // Read back what the provider actually accepted rather than trusting the
  // call returning. A 200 with no message id is not a delivery, and treating
  // it as one is how a campaign reports success into an empty mailbox.
  if (!result.providerMessageId) {
    return { sent: false, reason: 'The email provider accepted the request but returned no message id, so nothing can be confirmed.' };
  }

  // Nothing left the building. Recorded as queued with the reason attached, so
  // it is visible work with a way back rather than a message the system
  // believes it sent — and never marked AWAITING_RESPONSE, because nobody is
  // going to respond to something that was never delivered.
  if (result.status === 'suppressed') {
    await prisma.message.create({
      data: {
        orgId: options.orgId,
        routeId: room.routeId,
        contactId: contact.id,
        companyId: contact.companyId,
        senderId: options.senderId ?? null,
        channel: 'EMAIL',
        direction: 'outbound',
        status: 'QUEUED',
        subject: draft.subject,
        body: draft.body,
        provider: getEmail().name,
        providerMessageId: result.providerMessageId,
        sentAt: null,
        outcome: 'UNDELIVERABLE',
        failureReason: result.reason ?? 'No transport accepted this message.',
      },
    });
    return { sent: false, reason: result.reason ?? 'No email transport is configured, so nothing was sent.' };
  }

  const message = await prisma.message.create({
    data: {
      orgId: options.orgId,
      routeId: room.routeId,
      contactId: contact.id,
      companyId: contact.companyId,
      senderId: options.senderId ?? null,
      channel: 'EMAIL',
      direction: 'outbound',
      status: 'SENT',
      subject: draft.subject,
      body: draft.body,
      provider: getEmail().name,
      providerMessageId: result.providerMessageId,
      sentAt: new Date(),
      outcome: 'AWAITING_RESPONSE',
      costCents: config.outreachCosts.emailPerMessage * 100,
    },
  });

  await prisma.$transaction(async (tx) => {
    await recordDealEvent(tx, {
      orgId: options.orgId,
      routeId: room.routeId,
      kind: 'room.emailed',
      actorId: options.senderId,
      subjectType: 'RouteQuote',
      subjectId: room.id,
      // Audience and confidence are kept with the send, so a reply rate can
      // later be read per audience type rather than in one meaningless average.
      summary: `Deal room emailed to a ${choice.audience.toLowerCase().replace(/_/g, ' ')}.`,
      after: {
        audience: choice.audience,
        confidence: choice.confidence,
        hasName: choice.hasName,
        providerMessageId: result.providerMessageId,
      },
      evidence: choice.reason,
      confidence: choice.confidence,
      correlationId: newCorrelationId(),
    });
  });

  return { sent: true, messageId: message.id, audience: choice.audience };
}

function lowerFirst(text: string): string {
  return text.charAt(0).toLowerCase() + text.slice(1);
}

function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1).trimEnd()}…`;
}
