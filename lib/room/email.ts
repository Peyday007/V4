/**
 * The message that carries a Deal Room.
 *
 * Everything in it is assembled from records. There is no template with a
 * paragraph of persuasion and a merge field, because that is what produces the
 * mail everyone in this industry deletes — and because a sentence we cannot
 * trace to a record is a sentence we cannot defend when somebody replies asking
 * where we got it.
 *
 * The greeting is generated by code rather than pulled from data, for a
 * specific reason the previous system learned expensively: "Hi ," and "Hi
 * Facilities Department Contact," both went out, and both told the recipient
 * exactly how much attention they were getting.
 */

export type Audience = 'VERIFIED_DECISION_MAKER' | 'NAMED_CONTACT' | 'PUBLISHED_PERSONAL' | 'GENERIC_INBOX';

export type AudienceChoice = {
  contact: Contact;
  audience: Audience;
  /** Why this address and not another. Stored with the message. */
  reason: string;
  /** Whether we hold a usable name for a greeting. */
  hasName: boolean;
  confidence: 'verified' | 'asserted' | 'inferred';
};

/**
 * Pick who to write to.
 *
 * The order is not a preference, it is a quality ladder. A verified
 * decision-maker is somebody a person established decides; a named contact is
 * somebody we hold a name and a role for; a published personal address is one
 * an individual owns; a generic inbox is a room with nobody's name on the door.
 * Sending to the last of those is sometimes right and always worse, so it
 * happens only where an operator has configured it.
 */
export function chooseAudience(
  contacts: Contact[],
  options: { allowGenericInbox: boolean },
): AudienceChoice | null {
  const emailable = contacts.filter(
    (c) => c.email
      && c.consentToEmail
      && c.email.includes('@')
      // A known-bad address is the one thing worse than no address: it costs a
      // send, damages the sending domain, and reports as delivered.
      && c.verificationStatus !== 'INVALID',
  );
  if (emailable.length === 0) return null;

  const named = (c: Contact) => Boolean(c.firstName?.trim()) && !isPlaceholderName(c.firstName);

  const verified = emailable.find((c) => c.isDecisionMaker && isVerified(c) && named(c));
  if (verified) {
    return {
      contact: verified,
      audience: 'VERIFIED_DECISION_MAKER',
      reason: 'A person established that this contact decides, and the address has been verified.',
      hasName: true,
      confidence: 'verified',
    };
  }

  const namedContact = emailable.find((c) => named(c) && !isGenericAddress(c.email!));
  if (namedContact) {
    return {
      contact: namedContact,
      audience: namedContact.isDecisionMaker ? 'NAMED_CONTACT' : 'PUBLISHED_PERSONAL',
      reason: namedContact.isDecisionMaker
        ? 'Named contact recorded as a decision-maker, though the address has not been verified.'
        : 'A named individual at the organisation. Not established as the person who decides.',
      hasName: true,
      confidence: isVerified(namedContact) ? 'verified' : 'asserted',
    };
  }

  const personal = emailable.find((c) => !isGenericAddress(c.email!));
  if (personal) {
    return {
      contact: personal,
      audience: 'PUBLISHED_PERSONAL',
      reason: 'A published individual address. We do not hold a usable name for it.',
      hasName: false,
      confidence: 'inferred',
    };
  }

  if (!options.allowGenericInbox) return null;

  return {
    contact: emailable[0],
    audience: 'GENERIC_INBOX',
    reason: 'Only a general inbox is on file. Sent because the organisation has enabled generic-inbox fallback.',
    hasName: false,
    confidence: 'inferred',
  };
}

/**
 * Verified by somebody, by either route.
 *
 * `INVALID` is deliberately not a form of verification: a bounced address is
 * the most confirmed a record can be and the least sendable.
 */
function isVerified(contact: Contact): boolean {
  return contact.verificationStatus === 'VERIFIED_BY_CALL'
    || contact.verificationStatus === 'VERIFIED_BY_SOURCE';
}

/** info@, sales@ and friends: a room, not a person. */
export function isGenericAddress(email: string): boolean {
  const local = email.split('@')[0]?.toLowerCase() ?? '';
  return [
    'info', 'sales', 'contact', 'hello', 'admin', 'office', 'enquiries', 'inquiries',
    'support', 'help', 'team', 'mail', 'general', 'reception', 'purchasing', 'accounts',
  ].includes(local);
}

/**
 * Names that are not names.
 *
 * Directory imports are full of these. Greeting somebody as "Owner" is worse
 * than not greeting them by name at all, because it advertises that a machine
 * filled the field.
 */
function isPlaceholderName(name: string | null | undefined): boolean {
  if (!name) return true;
  const trimmed = name.trim().toLowerCase();
  if (trimmed.length < 2) return true;
  return [
    'owner', 'manager', 'contact', 'admin', 'info', 'n/a', 'na', 'unknown',
    'director', 'purchasing', 'facilities', 'the', 'team', 'department',
  ].includes(trimmed);
}

/**
 * A greeting that is never wrong.
 *
 * Generated here rather than templated, so there is exactly one place where a
 * missing first name turns into "Hello," instead of "Hi ,". The plain version
 * is not a degraded fallback — it is a perfectly ordinary way to open a letter,
 * and it is what a person would write.
 */
export function greeting(choice: AudienceChoice): string {
  if (!choice.hasName) return 'Hello,';
  const first = choice.contact.firstName.trim().split(/\s+/)[0];
  return `Hi ${first},`;
}

