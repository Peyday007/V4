// The message
// ---------------------------------------------------------------------------

export type DraftedEmail = {
  subject: string;
  body: string;
  /** Every claim in the body, and the record it came from. */
  grounding: string[];
  /** Reasons this should not be sent as drafted. Non-empty blocks autonomous send. */
  blockers: string[];
};

/**
 * Draft the message from the room's own snapshot.
 *
 * Nothing is invented here, and that constraint produces the shape of it: a
 * dated observation, what we think it means labelled as what we think, the one
 * thing we are asking for, and the link. If the room has no dated event behind
 * it there is no first line to write, and this says so rather than reaching for
 * a generic opener.
 */
export function draftRoomEmail(input: {
  content: RoomContent;
  choice: AudienceChoice;
  url: string;
  senderName: string;
}): DraftedEmail {
  const { content, choice } = input;
  const grounding: string[] = [];
  const blockers: string[] = [];

  if (!content.why) {
    blockers.push('There is no dated event behind this room, so the opening line would be an assertion with nothing under it.');
  }
  if (content.tooThinToSend) {
    blockers.push(...content.thinReasons);
  }
  if (choice.audience === 'GENERIC_INBOX') {
    grounding.push('Sent to a general inbox: nobody specific is being addressed, and the message says so.');
  }

  const lines: string[] = [greeting(choice), ''];

  if (content.why) {
    lines.push(
      `${content.why.text} — dated ${content.why.eventDate}, from ${content.why.source}.`,
      '',
    );
    grounding.push(`Opening line from the demand event dated ${content.why.eventDate}.`);
  }

  // The one inference, stated as one. A prospect can correct an assumption
  // they can see; they cannot correct one dressed up as a finding.
  const firstOurs = content.sections.flatMap((s) => s.ours).find(Boolean);
  if (firstOurs) {
    lines.push(`We think that means ${lowerFirst(firstOurs)} We may have that wrong.`, '');
    grounding.push('The inference is labelled as ours in the body, matching the room.');
  }

  const questions = content.sections.flatMap((s) => s.questions).slice(0, 2);
  if (questions.length > 0) {
    lines.push('What we cannot tell from the record:', ...questions.map((q) => `  - ${q}`), '');
    grounding.push(`${questions.length} open question(s) taken from the requirement gaps.`);
  }

  lines.push(
    content.proofStep.ask,
    `That commits you to: ${lowerFirst(content.proofStep.commitment)}`,
    '',
    'The detail, and where each part of it came from:',
    input.url,
    '',
    'If this is not you, or not relevant, replying with that is genuinely useful and we will stop.',
    '',
    input.senderName,
  );
  grounding.push(`The ask is the recommended proof step (${content.proofStep.kind}).`);

  const subject = content.why
    ? `${content.organisation} — ${truncate(content.why.text, 60)}`
    : `${content.organisation} — a question about ${content.route.toLowerCase()}`;

  return { subject, body: lines.join('\n'), grounding, blockers };
}

